#  FEATURES
#
#   Real-time emotion detection (7 emotions) via MediaPipe Face Mesh
#   Confidence scoring  (eye contact + head stability + expression)
#   Stress analysis     (facial tension + fear/anger probability)
#   Attention tracking  (gaze direction + eye openness)
#   Live webcam feed with annotated bounding boxes
#   Emotion timeline chart  (live + per-session history)
#   PDF report generation with ReportLab
#   SQLite session database
#   Multi-face support
#   Interview analytics dashboard
#
#  TECH STACK 
#
#   Frontend : HTML5 + CSS3 + JS 
#   Backend  : Flask (Python)
#   Vision   : OpenCV + MediaPipe Face Mesh (NO TensorFlow required)
#   Database : SQLite
#   Reports  : ReportLab PDF
#
# No model training required — zero TensorFlow/Keras dependency!
